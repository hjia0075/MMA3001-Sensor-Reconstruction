"""Offline reconstruction of environmental sensor outages.

Run ``python reconstruction.py prepare --input PATH`` then
``python reconstruction.py benchmark``. Ground truth always consists of
observations, never values generated by resampling/interpolation.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from time import perf_counter

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
METHODS = ("forward_fill", "linear", "cubic", "pchip")


def prepare(input_path: Path, output: Path, start: str, end: str) -> None:
    """Decode JSON and audit all rows; retain unambiguous observations.

    Args:
        input_path: Original CSV, read without modification.
        output: Destination directory for audit and cleaned CSV.
        start: Inclusive UTC study date.
        end: Exclusive UTC study date.

    Conflicting values at the same sensor/variable/time are excluded rather
    than averaged. Identical repeated observations are collapsed.
    """
    output.mkdir(parents=True, exist_ok=True)
    observations = {}
    raw_rows = malformed = repeated = invalid = missing_values = 0
    units = {}
    for chunk in pd.read_csv(input_path, chunksize=20000, dtype={"sensorid": str}):
        for sid, payload in zip(chunk.sensorid, chunk.jsondata):
            raw_rows += 1
            try:
                parsed = json.loads(payload)
                for item in parsed:
                    variable = item["variable"]["name"]
                    units.setdefault(variable, set()).add(item["variable"]["unit"])
                    for point in item["values"]:
                        if "value" not in point or point["value"] is None:
                            missing_values += 1
                            continue
                        timestamp, value = float(point["time"]), float(point["value"])
                        if not np.isfinite(timestamp) or not np.isfinite(value):
                            invalid += 1
                            continue
                        key = (sid, variable, timestamp)
                        if key not in observations:
                            observations[key] = {value}
                        else:
                            repeated += value in observations[key]
                            observations[key].add(value)
            except (ValueError, TypeError, KeyError):
                malformed += 1
    conflicts = sum(len(v) > 1 for v in observations.values())
    records = [(sid, var, t, next(iter(v)))
               for (sid, var, t), v in observations.items() if len(v) == 1]
    data = pd.DataFrame(records, columns=["sensor_id", "variable", "time_s", "value"])
    data["timestamp_utc"] = pd.to_datetime(data.time_s, unit="s", utc=True)
    first, last = str(data.timestamp_utc.min()), str(data.timestamp_utc.max())
    data = data[(data.timestamp_utc >= pd.Timestamp(start, tz="UTC")) &
                (data.timestamp_utc < pd.Timestamp(end, tz="UTC"))].copy()
    # Broad screening bounds are data-quality rules, not physical rate limits.
    valid = ((data.variable != "Temperature") | data.value.between(-20, 60)) & \
            ((data.variable != "Carbon dioxide") | data.value.between(0, 20000))
    rejected_bounds = int((~valid).sum())
    data = data[valid].sort_values(["sensor_id", "variable", "time_s"])
    data.to_csv(output / "observations.csv", index=False)
    cadence = []
    for (sid, var), group in data.groupby(["sensor_id", "variable"]):
        dt = np.diff(group.time_s.to_numpy())
        cadence.append({"sensor_id": sid, "variable": var, "n": len(group),
                        "start": str(group.timestamp_utc.min()),
                        "end": str(group.timestamp_utc.max()),
                        "median_interval_s": float(np.median(dt)) if len(dt) else None,
                        "p95_interval_s": float(np.quantile(dt, .95)) if len(dt) else None})
    pd.DataFrame(cadence).to_csv(output / "coverage.csv", index=False)
    audit = {"source": input_path.name, "raw_rows": raw_rows,
             "malformed_payloads": malformed, "missing_value_points": missing_values,
             "invalid_numeric_points": invalid,
             "repeated_identical_points": int(repeated), "conflicting_keys_excluded": conflicts,
             "source_measurement_start_utc": first, "source_measurement_end_utc": last,
             "study_start_inclusive_utc": start, "study_end_exclusive_utc": end,
             "screened_points": rejected_bounds, "study_observations": len(data),
             "units": {k: sorted(v) for k, v in units.items()}}
    (output / "audit.json").write_text(json.dumps(audit, indent=2), encoding="utf-8")
    print(json.dumps(audit, indent=2))


def reconstruct(x: np.ndarray, y: np.ndarray, query: np.ndarray, method: str) -> np.ndarray:
    """Interpolate strictly ordered finite data inside the observed domain.

    Times use seconds relative to a local origin. Values retain source units.
    Raises ValueError for invalid arrays, duplicate times or extrapolation.
    Cubic splines use natural (zero endpoint second derivative) conditions.
    """
    from scipy.interpolate import CubicSpline, PchipInterpolator
    x, y, query = [np.asarray(a, dtype=float) for a in (x, y, query)]
    if any(a.ndim != 1 for a in (x, y, query)) or len(x) != len(y) or len(x) < 2:
        raise ValueError("Require matching 1-D training arrays with at least two nodes")
    if not all(np.isfinite(a).all() for a in (x, y, query)) or np.any(np.diff(x) <= 0):
        raise ValueError("Require finite values and strictly increasing node times")
    if np.any(query < x[0]) or np.any(query > x[-1]):
        raise ValueError("Extrapolation is not supported")
    if method == "forward_fill":
        return y[np.searchsorted(x, query, side="right") - 1]
    if method == "linear":
        return np.interp(query, x, y)
    if method == "cubic":
        return CubicSpline(x, y, bc_type="natural", extrapolate=False)(query)
    if method == "pchip":
        return PchipInterpolator(x, y, extrapolate=False)(query)
    raise ValueError(f"Unknown method: {method}")


def candidate_windows(t: np.ndarray, duration_s: float, context: int = 4) -> list[tuple[int, int]]:
    """Find outage windows with >=3 hidden observations and complete context.

    Outage interval starts at an observed point and lasts duration_s. Its
    right edge is exclusive. Every interval in the original context must be
    <=1.5 times the sensor's median cadence. Windows are evaluated at the
    original measurement times, without fabricated grid ground truth.
    """
    t = np.asarray(t, dtype=float)
    if len(t) < 2 * context + 3:
        return []
    cadence = np.median(np.diff(t))
    result = []
    for i in range(context, len(t) - context):
        j = int(np.searchsorted(t, t[i] + duration_s, side="left"))
        if j - i < 3 or j + context > len(t):
            continue
        if np.max(np.diff(t[i-context:j+context])) <= 1.5 * cadence:
            result.append((i, j))
    return result


def benchmark(data_path: Path, output: Path, variable: str, durations: list[int],
              n_windows: int, seed: int) -> None:
    """Compare identical nonoverlapping masks across sensors and time splits.

    The first 60% of each sensor's calendar span is development, next 20%
    validation, final 20% test. Boundary-straddling context is excluded.
    Runtime is the median of five build-and-evaluate runs, excludes I/O.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy.integrate import trapezoid

    output.mkdir(parents=True, exist_ok=True)
    data = pd.read_csv(data_path, dtype={"sensor_id": str})
    data = data[data.variable == variable]
    if data.empty:
        raise ValueError(f"No observations for {variable}")
    rng = np.random.default_rng(seed)
    results, masks, examples, pointwise = [], [], {}, []
    for sid, group in data.groupby("sensor_id"):
        group = group.sort_values("time_s")
        whole_t = group.time_s.to_numpy()
        a, b = whole_t[0], whole_t[-1]
        edges = [a, a + .6*(b-a), a + .8*(b-a), b + 1]
        for split, left, right in zip(("development", "validation", "test"), edges[:-1], edges[1:]):
            g = group[(group.time_s >= left) & (group.time_s < right)]
            t, y = g.time_s.to_numpy(), g.value.to_numpy()
            for minutes in durations:
                candidates = candidate_windows(t, minutes * 60)
                occupied = set()
                selected = []
                for index in rng.permutation(len(candidates)):
                    i, j = candidates[index]
                    used = set(range(i-4, j+4))
                    if used.isdisjoint(occupied):
                        selected.append((i, j)); occupied.update(used)
                    if len(selected) >= n_windows:
                        break
                masks.append({"sensor_id": sid, "split": split, "gap_minutes": minutes,
                              "candidate_windows": len(candidates), "selected_windows": len(selected)})
                for window_id, (i, j) in enumerate(selected):
                    indices = np.r_[np.arange(i-4, i), np.arange(j, j+4)]
                    x, known = t[indices] - t[i-1], y[indices]
                    q, truth = t[i:j] - t[i-1], y[i:j]
                    for method in METHODS:
                        elapsed = []
                        for _ in range(5):
                            tic = perf_counter(); pred = reconstruct(x, known, q, method)
                            elapsed.append(perf_counter()-tic)
                        error = pred-truth
                        for timestamp, observed, predicted in zip(t[i:j], truth, pred):
                            pointwise.append({"sensor_id": sid, "split": split,
                                "gap_minutes": minutes, "window_id": window_id,
                                "window_start_utc": str(pd.to_datetime(t[i], unit="s", utc=True)),
                                "timestamp_utc": str(pd.to_datetime(timestamp, unit="s", utc=True)),
                                "method": method, "original_value": float(observed),
                                "prediction": float(predicted),
                                "signed_error": float(predicted-observed),
                                "absolute_error": float(abs(predicted-observed))})
                        # Integral spans last pre-outage to first post-outage node.
                        ix = t[i-1:j+1] - t[i-1]
                        actual = trapezoid(y[i-1:j+1], ix) / 3600
                        estimated = trapezoid(np.r_[y[i-1], pred, y[j]], ix) / 3600
                        slope = np.diff(np.r_[y[i-1], pred, y[j]]) / (np.diff(ix)/60)
                        low, high = min(y[i-1], y[j]), max(y[i-1], y[j])
                        results.append({"sensor_id": sid, "split": split,
                            "gap_minutes": minutes, "window_id": window_id,
                            "start_utc": str(pd.to_datetime(t[i], unit="s", utc=True)),
                            "hidden_points": len(truth), "method": method,
                            "mae": float(np.mean(abs(error))), "rmse": float(np.sqrt(np.mean(error**2))),
                            "max_abs_error": float(np.max(abs(error))),
                            "runtime_ms": float(np.median(elapsed)*1000),
                            "absolute_integral_error_unit_hours": float(abs(estimated-actual)),
                            "endpoint_range_exceedance_fraction": float(np.mean((pred < low-1e-9)|(pred > high+1e-9))),
                            "max_abs_reconstructed_rate_per_min": float(np.max(abs(slope)))})
                        if split == "test":
                            key = (sid, minutes)
                            if key not in examples:
                                examples[key] = {"t": t[i-4:j+4], "y": y[i-4:j+4],
                                                 "q": t[i:j], "pred": {}}
                            if examples[key]["q"][0] == t[i]:
                                examples[key]["pred"][method] = pred
    pd.DataFrame(masks).to_csv(output / "mask_coverage.csv", index=False)
    r = pd.DataFrame(results)
    if r.empty:
        raise ValueError("No eligible windows; inspect cadence and requested gap lengths")
    r.to_csv(output / "window_metrics.csv", index=False)
    pd.DataFrame(pointwise).to_csv(output / "pointwise_predictions.csv", index=False)
    summary = r.groupby(["split", "gap_minutes", "method"]).agg(
        windows=("mae", "size"), mean_mae=("mae", "mean"), median_mae=("mae", "median"),
        mean_window_rmse=("rmse", "mean"), median_runtime_ms=("runtime_ms", "median"),
        mean_integral_error=("absolute_integral_error_unit_hours", "mean"),
        mean_endpoint_range_exceedance=("endpoint_range_exceedance_fraction", "mean")).reset_index()
    summary.to_csv(output / "summary.csv", index=False)
    config = {"variable": variable, "durations_minutes": durations, "seed": seed,
              "requested_windows_per_sensor_split_duration": n_windows,
              "context_nodes_each_side": 4, "continuity_factor": 1.5,
              "cubic_boundary_condition": "natural", "runtime_repeats": 5,
              "interpretation": "offline reconstruction; observed noisy values are reference, not physical truth"}
    (output / "experiment_config.json").write_text(json.dumps(config, indent=2))
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    test = summary[summary.split == "test"]
    for method in METHODS:
        s = test[test.method == method]
        axes[0].plot(s.gap_minutes, s.mean_mae, "o-", label=method)
        axes[1].plot(s.gap_minutes, s.median_runtime_ms, "o-", label=method)
    axes[0].set_ylabel(f"Mean window MAE ({'deg C' if variable == 'Temperature' else 'source units'})")
    axes[1].set_ylabel("Median build + evaluate time (ms)")
    for ax in axes:
        ax.set_xlabel("Masked outage duration (minutes)"); ax.grid(alpha=.25)
    axes[0].legend(); fig.tight_layout(); fig.savefig(output / "comparison.png", dpi=180); plt.close(fig)
    # One example per available duration, using actual observed reference points.
    for minutes in durations:
        keys = [k for k in examples if k[1] == minutes]
        if not keys:
            continue
        sid, _ = keys[0]; ex = examples[keys[0]]; origin = ex["t"][0]
        fig, ax = plt.subplots(figsize=(9, 4))
        ax.plot((ex["t"]-origin)/60, ex["y"], "k.-", label="Observed reference")
        ax.axvspan((ex["q"][0]-origin)/60, (ex["q"][-1]-origin)/60, color="grey", alpha=.15)
        for method, pred in ex["pred"].items():
            ax.plot((ex["q"]-origin)/60, pred, ".--", label=method)
        ax.set(xlabel="Minutes from local origin", ylabel=variable,
               title=f"{sid}: {minutes}-minute test mask")
        ax.legend(); fig.tight_layout(); fig.savefig(output / f"example_{minutes}min.png", dpi=180); plt.close(fig)
    print(test.to_string(index=False))


def main() -> None:
    """Parse command-line arguments and run a reproducible pipeline stage."""
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("prepare")
    p.add_argument("--input", type=Path, required=True)
    p.add_argument("--output", type=Path, default=ROOT / "data/processed")
    p.add_argument("--start", default="2024-05-01")
    p.add_argument("--end", default="2025-01-01")
    p = sub.add_parser("benchmark")
    p.add_argument("--data", type=Path, default=ROOT / "data/processed/observations.csv")
    p.add_argument("--output", type=Path, default=ROOT / "results/temperature")
    p.add_argument("--variable", default="Temperature")
    p.add_argument("--durations", type=int, nargs="+", default=[30, 60, 120])
    p.add_argument("--windows", type=int, default=30)
    p.add_argument("--seed", type=int, default=3001)
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.input, args.output, args.start, args.end)
    else:
        if args.windows < 1 or any(d <= 0 for d in args.durations):
            parser.error("Positive window count and gap durations required")
        benchmark(args.data, args.output, args.variable, args.durations, args.windows, args.seed)


if __name__ == "__main__":
    main()
